"""Fit the offline ETA fallback against real road routes.

When the app cannot reach any router (offline, server down) it estimates a
trip from the straight-line distance. This script measures how real roads
compare: it samples random trips around each city centre, asks the free
OSRM/Valhalla servers for the road route, and fits

  - detour_factor   median(road distance / straight distance)
  - speed bands     road distance / road duration per distance band
                    (aggregate ratio, robust to short-trip noise), slowed by
                    --traffic-factor because OSRM durations are free-flow
  - fixed overhead  parking + walking to the door (configurable)

and rewrites src/shared/tracking/etaCalibration.generated.ts. Live trips do
not depend on this file's accuracy -- the TripEngine re-learns pace from the
actual drive -- it only sets the starting estimate when no route exists.

Usage:
  py tools/geo/calibrate_eta.py                       # default DACH cities
  py tools/geo/calibrate_eta.py --samples 40 --city "Nuremberg:11.0767,49.4521"
  py tools/geo/calibrate_eta.py --dry-run             # print, do not write
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import math
import random
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from geo_core import CALIBRATION_TS, destination_point, haversine_m  # noqa: E402
from routing_client import route  # noqa: E402

DEFAULT_CITIES = {
    "Nuremberg": (11.0767, 49.4521),
    "Munich": (11.5755, 48.1374),
    "Berlin": (13.4050, 52.5200),
    "Hamburg": (9.9937, 53.5511),
    "Vienna": (16.3738, 48.2082),
    "Zurich": (8.5417, 47.3769),
}
BAND_LIMITS_M = [2_000, 5_000, 12_000, math.inf]


def sample_pairs(center, n, rng):
    """Log-uniform trip lengths 0.6-18 km, which is where real barber trips live."""
    for _ in range(n):
        origin = destination_point(center, rng.uniform(0, 360), rng.uniform(0, 4_000))
        length = math.exp(rng.uniform(math.log(600), math.log(18_000)))
        yield origin, destination_point(origin, rng.uniform(0, 360), length)


def fit(samples, traffic_factor, overhead_s):
    ratios = [s["road_m"] / s["straight_m"] for s in samples if s["straight_m"] > 200]
    detour = statistics.median(ratios)
    bands = []
    lower = 0.0
    for upper in BAND_LIMITS_M:
        in_band = [s for s in samples if lower < s["road_m"] <= upper]
        if len(in_band) >= 3:
            speed = sum(s["road_m"] for s in in_band) / sum(s["road_s"] for s in in_band)
        else:  # too few samples: borrow the overall aggregate speed
            speed = sum(s["road_m"] for s in samples) / sum(s["road_s"] for s in samples)
        bands.append({
            "maxDistanceM": None if math.isinf(upper) else upper,
            "speedMps": round(speed / traffic_factor, 2),
            "samples": len(in_band),
        })
        lower = upper
    # Enforce monotonic speeds (longer trips use faster roads) so the
    # estimate never gets shorter when the distance gets longer.
    for i in range(1, len(bands)):
        bands[i]["speedMps"] = max(bands[i]["speedMps"], bands[i - 1]["speedMps"])
    p90 = sorted(ratios)[int(0.9 * (len(ratios) - 1))]
    return {
        "detourFactor": round(detour, 3),
        "speedBands": bands,
        "fixedOverheadS": overhead_s,
        "_stats": {"samples": len(samples), "detourP90": round(p90, 3)},
    }


def render_ts(result, cities, traffic_factor):
    payload = {
        "detourFactor": result["detourFactor"],
        "speedBands": [
            {"maxDistanceM": b["maxDistanceM"] if b["maxDistanceM"] is not None else 1e12, "speedMps": b["speedMps"]}
            for b in result["speedBands"]
        ],
        "fixedOverheadS": result["fixedOverheadS"],
    }
    stats = result["_stats"]
    return (
        "// GENERATED by tools/geo/calibrate_eta.py -- do not edit by hand; re-run the script.\n"
        f"// Generated {dt.date.today().isoformat()} from {stats['samples']} free OSRM/Valhalla routes in "
        f"{', '.join(cities)}.\n"
        f"// Free-flow router speeds slowed by a traffic factor of {traffic_factor}; detour P90 = {stats['detourP90']}.\n"
        "// Only the offline fallback uses these numbers: live trips re-learn pace from the drive itself.\n\n"
        "export interface EtaCalibration {\n"
        "  /** Road distance / straight-line distance. */\n"
        "  detourFactor: number;\n"
        "  /** Average door-to-door speed by road distance, ascending maxDistanceM. */\n"
        "  speedBands: { maxDistanceM: number; speedMps: number }[];\n"
        "  /** Parking and walking to the door. */\n"
        "  fixedOverheadS: number;\n"
        "}\n\n"
        f"export const ETA_CALIBRATION: EtaCalibration = /*JSON*/{json.dumps(payload)}/*END*/;\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--samples", type=int, default=12, help="trips per city (each is one polite request)")
    parser.add_argument("--city", action="append", help='extra/override city as "Name:lng,lat"')
    parser.add_argument("--traffic-factor", type=float, default=1.2)
    parser.add_argument("--overhead-s", type=float, default=90)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    cities = dict(DEFAULT_CITIES)
    if args.city:
        cities = {}
        for spec in args.city:
            name, coords = spec.split(":")
            lng, lat = (float(v) for v in coords.split(","))
            cities[name] = (lng, lat)

    rng = random.Random(args.seed)
    samples = []
    for name, center in cities.items():
        ok = 0
        for origin, dest in sample_pairs(center, args.samples, rng):
            result = route(origin, dest)
            if result is None or result.distance_m < 100:
                continue
            samples.append({
                "straight_m": haversine_m(origin, dest),
                "road_m": result.distance_m,
                "road_s": result.duration_s,
            })
            ok += 1
        print(f"{name:<12} {ok}/{args.samples} routes", flush=True)

    if len(samples) < 10:
        print("Too few routes to fit a calibration (routers unreachable?). Nothing written.", file=sys.stderr)
        return 1

    result = fit(samples, args.traffic_factor, args.overhead_s)
    print(json.dumps(result, indent=2))
    if args.dry_run:
        return 0
    CALIBRATION_TS.write_text(render_ts(result, list(cities), args.traffic_factor), encoding="utf-8")
    print(f"Wrote {CALIBRATION_TS}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
